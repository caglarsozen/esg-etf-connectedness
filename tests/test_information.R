for(f in sort(list.files('R',pattern='[.]R$',full.names=TRUE)))source(f)
source('benchmarks/gaussian_dcc.R')
checks<-list();check<-function(n,ok){checks[[length(checks)+1]]<<-data.frame(check=n,pass=isTRUE(ok));stopifnot(isTRUE(ok))}
pr<-revision_protocol(getwd());d<-revision_read('input/archived_returns.csv',as.Date('2023-04-28'))
cut<-which(d$dates==as.Date('2023-02-28'));R2<-d$R
R2[(cut+1):nrow(R2),]<-R2[(cut+1):nrow(R2),]+.12
b1<-revision_bundle(d$R,d$dates,cut,pr$models[2,],pr)
b2<-revision_bundle(R2,d$dates,cut,pr$models[2,],pr)
check('future_perturbation_forecast',identical(b1$forecast,b2$forecast))
check('future_perturbation_regime',identical(b1$next_prob,b2$next_prob))
check('future_perturbation_network',identical(b1$network$score,b2$network$score))
a1<-revision_targets(b1,pr);a2<-revision_targets(b2,pr)
check('future_perturbation_all_weights',max(abs(a1$weights-a2$weights))<1e-10)
s1<-revision_fsv_scale(d$R,.98,126);s2<-revision_fsv_scale(d$R[1:cut,],.98,126)
check('FSV_scale_prefix_invariance',identical(s1$D[1:cut,],s2$D))
check('FSV_next_scale_alignment',max(abs(s1$D[cut+1,]-s2$next_scale))<1e-10)
pk<-b1$packet;check('genuine_daily_lag_packets',all(pk$lag_time==pk$time-1L))
set.seed(731);Y<-matrix(rnorm(900),300,3)
ab<-c(.05,.9);theta<-c(log(.1),dcc_start(ab[1],ab[2]));h<-dcc_garch_path(Y[,1],theta)
check('GARCH_parameters_recovered',max(abs(c(h$alpha,h$beta)-ab))<1e-10)
check('GARCH_forecast_recursion',abs(h$next_h-(.1+.05*Y[300,1]^2+.9*h$h[300]))<1e-10)
q<-dcc_correlation_path(Y,dcc_start(.03,.95))
check('DCC_corr_diagonal',max(abs(diag(q$forecast)-1))<1e-10)
check('DCC_corr_SPD',min(eigen(q$forecast,symmetric=TRUE)$values)>0)
freeze<-readRDS('outputs/FROZEN_HISTORICAL_DESIGN.rds')
check('frozen_historical_sources_unchanged',identical(tools::md5sum(names(freeze$source_md5)),freeze$source_md5))
esg_csv(do.call(rbind,checks),'outputs/INFORMATION_AND_BENCHMARK_CHECKS.csv')
cat(length(checks),'information/benchmark checks passed\n')
